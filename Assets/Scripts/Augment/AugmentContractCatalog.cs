    private static void AddCommon(
        List<AugmentContract> list,
        string id,
        AugmentTier tier,
        string name,
        string effect)
    {
        list.Add(
            new AugmentContract(
                id,
                tier,
                AugmentScope.Common,
                "",
                name,
                effect
            )
        );
    }

    private static void AddSet(
        List<AugmentContract> list,
        string summonName,
        (string name, string effect) t1,
        (string name, string effect) t2,
        (string name, string effect) t3,
        (string name, string effect) t4)
    {
        string safe =
            summonName.Replace(
                " ",
                "_"
            );

        list.Add(new AugmentContract("S_" + safe + "_T1", AugmentTier.T1, AugmentScope.SummonExclusive, summonName, t1.name, t1.effect));
        list.Add(new AugmentContract("S_" + safe + "_T2", AugmentTier.T2, AugmentScope.SummonExclusive, summonName, t2.name, t2.effect));
        list.Add(new AugmentContract("S_" + safe + "_T3", AugmentTier.T3, AugmentScope.SummonExclusive, summonName, t3.name, t3.effect));
        list.Add(new AugmentContract("S_" + safe + "_T4", AugmentTier.T4, AugmentScope.SummonExclusive, summonName, t4.name, t4.effect));
    }
